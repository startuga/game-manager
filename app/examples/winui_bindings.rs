//! Generates `app/src/winui_bindings.rs`: the few WinUI calls the app makes itself, because
//! windows-reactor has no API for them (`compact.rs` merges WinUI's Compact sizing into the
//! application's resources).
//!
//! The WinUI metadata is the reactor's own, from the windows-rs checkout that `Cargo.lock` pins
//! (`crates/tools/reactor-metadata/winmd`), found through `cargo metadata`, and the options are
//! those its binding tool uses (`crates/tools/reactor/src/main.rs`). Run it after updating
//! windows-rs: `cargo run -p app --example winui_bindings`.

#![allow(
    clippy::expect_used,
    reason = "a developer tool: stopping with the reason is the right response to a failure"
)]

use std::path::{Path, PathBuf};
use std::process::Command;

/// What the app calls, in windows-bindgen's filter syntax.
const FILTERS: [&str; 7] = [
    "Microsoft::UI::Xaml::Application::Current",
    "Microsoft::UI::Xaml::IApplication::get_Resources",
    "Microsoft::UI::Xaml::Markup::XamlReader::Load",
    "Microsoft::UI::Xaml::ResourceDictionary::CreateInstance",
    "Microsoft::UI::Xaml::IResourceDictionary::{get_MergedDictionaries, put_Source}",
    "Windows::Foundation::PropertyValue::CreateString",
    "Windows::Foundation::Uri::CreateUri",
];

/// The doc the generated file starts with (the project wants one on every source file).
const DOC: &str = "//! WinUI bindings for the calls windows-reactor has no API for (`compact.rs`).
//! Generated by `cargo run -p app --example winui_bindings`: do not edit by hand.

";

fn main() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let output = manifest.join("src").join("winui_bindings.rs");
    windows_bindgen::builder()
        .input(winmd_dir(manifest))
        .input_default()
        .output(&output)
        .minimal()
        .dead_code()
        .flat()
        .filters(FILTERS)
        .write();
    let generated = std::fs::read_to_string(&output)
        .expect("windows-bindgen wrote the file it was asked to write");
    std::fs::write(&output, format!("{DOC}{generated}")).expect("the bindings file is writable");
    println!("Wrote {}", output.display());
}

/// The WinUI `.winmd` files of the windows-reactor checkout in use.
fn winmd_dir(manifest: &Path) -> PathBuf {
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let metadata = Command::new(cargo)
        .args(["metadata", "--format-version", "1", "--manifest-path"])
        .arg(manifest.join("Cargo.toml"))
        .output()
        .expect("cargo metadata runs");
    assert!(metadata.status.success(), "cargo metadata failed");
    let metadata: serde_json::Value =
        serde_json::from_slice(&metadata.stdout).expect("cargo metadata prints JSON");
    let reactor = metadata["packages"]
        .as_array()
        .and_then(|packages| {
            packages
                .iter()
                .find(|package| package["name"] == "windows-reactor")
        })
        .and_then(|package| package["manifest_path"].as_str())
        .expect("the app depends on windows-reactor");
    // <checkout>\crates\libs\reactor\Cargo.toml -> <checkout>\crates
    let crates = Path::new(reactor)
        .ancestors()
        .nth(3)
        .expect("windows-reactor lives in crates\\libs\\reactor");
    let winmd = crates.join("tools").join("reactor-metadata").join("winmd");
    assert!(winmd.is_dir(), "no WinUI metadata in {}", winmd.display());
    winmd
}
